/**
 * Шаги ориентира за одну сессию таймера (FR-56, ADR-007): часть лога, пишутся, удаляются и переносятся вместе с ним.
 * Шаг — индекс в `guide.steps` с 0: у шага нет ключа, шаги различаются номером (Д-10).
 */
export interface ILogSteps {
  /**
   * Целые минуты каждого шага за эту сессию, по индексу шага; сумма равна `durationMin` лога (FR-56, FR-64).
   * Длина — не меньше `stepCount`: шаг, добавленный в ориентир во время сессии, получает свой индекс.
   */
  readonly minutes: readonly number[];
  /** Шаг, активный при старте сессии. */
  readonly startIndex: number;
  /** Шаг остановки: активный при «Стоп», «Переключиться» или «Засчитать». */
  readonly stopIndex: number;
  /** Сессия стартовала с подсказкой «Продолжить…» и продолжила круг (FR-57); false — начала новый круг. */
  readonly continuesCircle: boolean;
  /** Круг, в который сессия добавила минуты: общий у всех сессий одного круга, новый у сессии, начавшей круг. */
  readonly circleId: string;
  /** Лимит сессии в минутах — длина, с которой она запущена (FR-55). */
  readonly limitMin: number;
  /** Число шагов ориентира при старте сессии (FR-63). */
  readonly stepCount: number;
  /**
   * Шаг, первым набравший 1 мин (Q-021): время шага в этой сессии первым достигло 60 000 мс.
   * null — ни один шаг не набрал 1 мин. Правка минут лога его не меняет (FR-64, Q-025).
   */
  readonly firstMinuteIndex: number | null;
}
