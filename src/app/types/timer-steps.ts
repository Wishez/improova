/**
 * Шаги идущей сессии (FR-52…FR-56, ADR-007): хранятся в таймере и переживают перезагрузку.
 * Шаг — индекс в `guide.steps` с 0. При «Стоп» `startIndex`, `continuesCircle`, `circleId` и `stepCount`
 * переходят в `ILogSteps` лога без изменений, `firstMinuteIndex` — по правилу 6 ADR-007 на момент «Стоп»;
 * `itemId` таймера становится `itemId` лога, `plannedMin` — `limitMin`: у таймера с шагами это строка и число > 0.
 */
export interface ITimerSteps {
  /** Активный шаг: меняется только действием владельца (FR-52). */
  readonly activeIndex: number;
  /**
   * Время сессии без пауз, мс, отданное каждому шагу до последней смены шага.
   * Активный шаг получает сверх своего значения `elapsed − сумма spentMs`, поэтому минуты шагов в сумме всегда равны часам сессии.
   *
   * Инвариант длины (ADR-007, «Длина spentMs») — обязательство каждой записи таймера:
   * - с момента старта по элементу на каждый шаг: старт пишет нули длиной `stepCount`;
   * - переход на шаг за концом массива сначала дополняет его нулями до `activeIndex + 1`;
   * - массив не укорачивается, в том числе при укороченном ориентире (FR-63), значения не уменьшаются (Q-032).
   *
   * Поэтому `activeIndex`, `startIndex` и записанный `firstMinuteIndex` всегда меньше длины массива, `stepCount` не больше её,
   * а «Стоп» даёт `minutes` лога той же длины. Таймер с более коротким массивом импорт отклоняет
   * (`meta[i].timer.steps.activeIndex`, `.startIndex`, `.stepCount`, `.firstMinuteIndex`).
   */
  readonly spentMs: readonly number[];
  /** Шаг, активный при старте сессии. */
  readonly startIndex: number;
  /** Сессия стартовала с подсказкой «Продолжить…» и продолжает круг (FR-57). */
  readonly continuesCircle: boolean;
  /** Круг, в который идут минуты сессии (см. `ILogSteps.circleId`). */
  readonly circleId: string;
  /** Число шагов ориентира при старте сессии (FR-63). */
  readonly stepCount: number;
  /**
   * Шаг, первым набравший 1 мин (Q-021), записанный при последней записи шагов. null — ещё не записан:
   * тогда набрать минуту первым может только активный шаг, и значение выводится из его времени (ADR-007, правило 6).
   */
  readonly firstMinuteIndex: number | null;
  /** Шаги, которым сигнал «Время шага по плану вышло» в этой сессии больше не подаётся: прозвучал или шаг стал активным с набранным планом (FR-54). */
  readonly planSignaled: readonly number[];
  /** «Время сессии вышло» уже прозвучало: после перезагрузки не повторяется (FR-55, Д-21). */
  readonly limitSignaled: boolean;
}
